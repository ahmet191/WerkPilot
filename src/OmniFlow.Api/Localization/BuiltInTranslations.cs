    public static IReadOnlyDictionary<string, string> For(string language)
        => All.TryGetValue(Normalize(language), out var map) ? map : All["en"];

    /// <summary>"tr-TR" and "TR" both resolve to "tr". "de-DE" and "DE" both resolve to "de".</summary>
    public static string Normalize(string language)
        => (language.Split('-').FirstOrDefault() ?? "en").ToLowerInvariant();

