    [HttpGet("{lang}")]
    public IActionResult GetTranslations(string lang)
    {
        var cleanLang = lang.Split('-').FirstOrDefault()?.ToLower() ?? "en";
        if (!Translations.TryGetValue(cleanLang, out var value))
        {
            return Ok(Translations["en"]);
        }
        return Ok(value);
    }
